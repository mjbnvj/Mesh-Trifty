create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  note text not null default '' check (char_length(note) <= 255),
  category text not null check (category in ('Clothing', 'Shoes', 'Accessories')),
  tag text not null default '' check (char_length(tag) <= 40),
  image text not null check (char_length(image) <= 2048),
  price numeric(10, 2) not null check (price > 0),
  stock integer not null default 0 check (stock >= 0),
  active boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique,
  user_id uuid not null references auth.users(id),
  customer_name text not null check (char_length(customer_name) between 1 and 80),
  email text not null check (char_length(email) between 3 and 254),
  address text not null check (char_length(address) between 1 and 120),
  city text not null check (char_length(city) between 1 and 60),
  postal text not null check (char_length(postal) between 1 and 20),
  payment_method text not null default 'Cash on delivery' check (payment_method = 'Cash on delivery'),
  subtotal numeric(10, 2) not null check (subtotal >= 0),
  shipping_fee numeric(10, 2) not null check (shipping_fee >= 0),
  total numeric(10, 2) not null check (total = subtotal + shipping_fee),
  status text not null default 'Pending'
    check (status in ('Pending', 'Processing', 'Shipped', 'Completed', 'Cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  size text not null,
  price numeric(10, 2) not null check (price > 0),
  quantity integer not null check (quantity between 1 and 20)
);

create table if not exists public.store_settings (
  id boolean primary key default true check (id),
  shipping_fee numeric(10, 2) not null default 100 check (shipping_fee >= 0 and shipping_fee <= 999999)
);

insert into public.store_settings (id, shipping_fee)
values (true, 100)
on conflict (id) do nothing;

alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.store_settings enable row level security;

drop policy if exists "Anyone can read active products" on public.products;
create policy "Anyone can read active products"
  on public.products for select
  to anon, authenticated
  using (active and stock > 0);

drop policy if exists "Customers can read their own orders" on public.orders;
create policy "Customers can read their own orders"
  on public.orders for select
  to authenticated
  using (
    (select auth.uid()) = user_id
    and (select auth.jwt() ->> 'aal') = 'aal2'
  );

drop policy if exists "Customers can read their own order items" on public.order_items;
create policy "Customers can read their own order items"
  on public.order_items for select
  to authenticated
  using (
    exists (
      select 1
      from public.orders
      where orders.id = order_items.order_id
        and orders.user_id = (select auth.uid())
        and (select auth.jwt() ->> 'aal') = 'aal2'
    )
  );

drop policy if exists "Anyone can read store shipping settings" on public.store_settings;
create policy "Anyone can read store shipping settings"
  on public.store_settings for select
  to anon, authenticated
  using (true);

create or replace function public.place_cod_order(
  p_user_id uuid,
  p_customer_name text,
  p_email text,
  p_address text,
  p_city text,
  p_postal text,
  p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  item jsonb;
  item_product_id bigint;
  item_size text;
  item_quantity integer;
  product_row public.products%rowtype;
  item_total numeric;
  order_subtotal numeric := 0;
  configured_shipping numeric(10, 2);
  created_order public.orders%rowtype;
  created_items jsonb := '[]'::jsonb;
begin
  if p_user_id is null
    or p_customer_name is null or char_length(btrim(p_customer_name)) not between 1 and 80
    or p_email is null or char_length(btrim(p_email)) not between 3 and 254
    or p_address is null or char_length(btrim(p_address)) not between 1 and 120
    or p_city is null or char_length(btrim(p_city)) not between 1 and 60
    or p_postal is null or char_length(btrim(p_postal)) not between 1 and 20 then
    raise exception using errcode = '22023', message = 'Enter valid delivery details.';
  end if;

  if p_items is null or jsonb_typeof(p_items) is distinct from 'array' then
    raise exception using errcode = '22023', message = 'Your cart is invalid.';
  end if;
  if jsonb_array_length(p_items) not between 1 and 50 then
    raise exception using errcode = '22023', message = 'Your cart is empty or too large.';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(p_items) as requested(value)
    group by value->>'product_id', value->>'size'
    having count(*) > 1
  ) then
    raise exception using errcode = '22023', message = 'Your cart contains duplicate item rows.';
  end if;

  select shipping_fee into configured_shipping
  from public.store_settings where id = true;
  if configured_shipping is null then
    raise exception using errcode = '55000', message = 'Store shipping is not configured.';
  end if;

  for item in select value from jsonb_array_elements(p_items)
  loop
    if jsonb_typeof(item) <> 'object'
      or coalesce(item->>'product_id', '') !~ '^[1-9][0-9]{0,17}$'
      or coalesce(item->>'quantity', '') !~ '^[1-9][0-9]?$'
      or coalesce(item->>'size', '') not in ('SMALL', 'MEDIUM', 'LARGE', 'XL', 'XXL', '39', '40', '41', '42', '43', '44', '45') then
      raise exception using errcode = '22023', message = 'Your cart contains an invalid item.';
    end if;

    item_product_id := (item->>'product_id')::bigint;
    item_quantity := (item->>'quantity')::integer;
    item_size := item->>'size';
    if item_quantity > 20 then
      raise exception using errcode = '22023', message = 'The quantity for an item is too large.';
    end if;

    select * into product_row
    from public.products
    where id = item_product_id and active
    for update;
    if not found or product_row.stock < item_quantity then
      raise exception using errcode = 'P0001', message = 'An item is unavailable or has insufficient stock.';
    end if;
    if (product_row.category = 'Clothing' and item_size not in ('SMALL', 'MEDIUM', 'LARGE', 'XL', 'XXL'))
      or (product_row.category = 'Shoes' and item_size not in ('39', '40', '41', '42', '43', '44', '45'))
      or (product_row.category = 'Accessories' and item_size not in ('MEDIUM', 'LARGE')) then
      raise exception using errcode = '22023', message = 'Choose a valid size for each item.';
    end if;

    item_total := product_row.price * item_quantity;
    if item_total > 99999999.99 - configured_shipping - order_subtotal then
      raise exception using errcode = '22023', message = 'The order total is too large.';
    end if;
    order_subtotal := order_subtotal + item_total;
    update public.products
    set stock = stock - item_quantity, updated_at = now()
    where id = product_row.id;
    created_items := created_items || jsonb_build_array(jsonb_build_object(
      'product_id', product_row.id,
      'product_name', product_row.name,
      'size', item_size,
      'price', product_row.price,
      'quantity', item_quantity
    ));
  end loop;

  insert into public.orders (
    order_number, user_id, customer_name, email, address, city, postal,
    payment_method, subtotal, shipping_fee, total
  )
  values (
    'MT-' || to_char(now() at time zone 'UTC', 'YYYYMMDD') || '-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8)),
    p_user_id, btrim(p_customer_name), lower(btrim(p_email)), btrim(p_address), btrim(p_city), btrim(p_postal),
    'Cash on delivery', order_subtotal, configured_shipping, order_subtotal + configured_shipping
  )
  returning * into created_order;

  for item in select value from jsonb_array_elements(created_items)
  loop
    insert into public.order_items (order_id, product_id, product_name, size, price, quantity)
    values (
      created_order.id,
      (item->>'product_id')::bigint,
      item->>'product_name',
      item->>'size',
      (item->>'price')::numeric,
      (item->>'quantity')::integer
    );
  end loop;

  return jsonb_build_object(
    'id', created_order.id,
    'order_number', created_order.order_number,
    'status', created_order.status,
    'subtotal', created_order.subtotal,
    'shipping_fee', created_order.shipping_fee,
    'total', created_order.total,
    'created_at', created_order.created_at,
    'items', created_items
  );
end;
$$;

revoke all on function public.place_cod_order(uuid, text, text, text, text, text, jsonb) from public, anon, authenticated;
grant execute on function public.place_cod_order(uuid, text, text, text, text, text, jsonb) to service_role;

create or replace function public.set_order_status(p_order_id uuid, p_status text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  order_row public.orders%rowtype;
  item_row record;
begin
  if p_status not in ('Pending', 'Processing', 'Shipped', 'Completed', 'Cancelled') then
    raise exception using errcode = '22023', message = 'Choose a valid order status.';
  end if;

  select * into order_row
  from public.orders
  where id = p_order_id
  for update;
  if not found then
    raise exception using errcode = 'P0002', message = 'Order not found.';
  end if;

  if order_row.status = p_status then
    return jsonb_build_object('id', order_row.id, 'order_number', order_row.order_number, 'status', order_row.status);
  end if;

  if order_row.status in ('Completed', 'Cancelled')
    or (order_row.status = 'Pending' and p_status not in ('Processing', 'Cancelled'))
    or (order_row.status = 'Processing' and p_status not in ('Shipped', 'Cancelled'))
    or (order_row.status = 'Shipped' and p_status <> 'Completed') then
    raise exception using errcode = '22023', message = 'That order status transition is not allowed.';
  end if;

  if p_status = 'Cancelled' then
    for item_row in
      select product_id, quantity
      from public.order_items
      where order_id = order_row.id and product_id is not null
      for update
    loop
      update public.products
      set stock = stock + item_row.quantity, updated_at = now()
      where id = item_row.product_id;
    end loop;
  end if;

  update public.orders
  set status = p_status
  where id = order_row.id
  returning * into order_row;

  return jsonb_build_object('id', order_row.id, 'order_number', order_row.order_number, 'status', order_row.status);
end;
$$;

revoke all on function public.set_order_status(uuid, text) from public, anon, authenticated;
grant execute on function public.set_order_status(uuid, text) to service_role;

grant select on public.products, public.orders, public.order_items, public.store_settings to anon, authenticated;
grant all on public.products, public.orders, public.order_items, public.store_settings to service_role;
grant usage, select on all sequences in schema public to service_role;

